"""Migration smoke test: fresh database, idempotency and model/migration parity."""

from __future__ import annotations

from alembic import command

from hcs_discovery.database.base import init_db
from hcs_discovery.database.migrations import alembic_config, current_revision


def test_fresh_database_is_at_head_and_idempotent(settings):
    revision = current_revision(settings)
    assert revision
    init_db(settings)
    assert current_revision(settings) == revision


def test_models_match_migrations(settings):
    config = alembic_config(settings)
    assert config is not None
    # Raises AutogenerateDiffsDetected if models drift from the migration chain.
    command.check(config)


def test_installed_wheel_layout_migrates_with_packaged_scripts(settings, tmp_path, monkeypatch):
    """A wheel has no alembic.ini; it must still run Alembic and record a revision."""
    import shutil

    from hcs_discovery.core.config import Settings
    from hcs_discovery.database import migrations

    packaged = tmp_path / "pkg" / "_alembic"
    shutil.copytree(migrations.PROJECT_ROOT / "migrations", packaged, ignore=shutil.ignore_patterns("__pycache__"))
    monkeypatch.setattr(migrations, "PROJECT_ROOT", tmp_path / "no-checkout")
    monkeypatch.setattr(migrations, "PACKAGED_SCRIPTS", packaged)

    wheel_settings = Settings(data_dir=tmp_path / "wheel-data")
    wheel_settings.ensure_dirs()
    assert migrations.upgrade_database(wheel_settings) == "alembic"
    assert migrations.current_revision(wheel_settings) == current_revision(settings)
