"""Migration smoke test: fresh database, idempotency and model/migration parity."""

from __future__ import annotations

from pathlib import Path

from alembic import command

from hcs_discovery.database.base import init_db
from hcs_discovery.database.migrations import alembic_config, current_revision


def test_fresh_database_is_at_head_and_idempotent(settings):
    revision = current_revision(settings)
    assert revision
    init_db(settings)
    assert current_revision(settings) == revision


def test_models_match_migrations(settings):
    config = alembic_config(settings)
    assert config is not None
    # Raises AutogenerateDiffsDetected if models drift from the migration chain.
    command.check(config)


def test_legacy_database_upgrades_without_losing_structure_rows(tmp_path: Path):
    """An existing v2.0.0 database gains `structures.license` and keeps its rows.

    The 2.0.0 schema had no license column, so this exercises a real upgrade path
    rather than a fresh install: an existing structure must survive and be labelled
    `unknown` instead of being dropped or back-filled with a guess.
    """
    import sqlalchemy as sa

    from hcs_discovery.core.config import Settings

    legacy = Settings(data_dir=tmp_path / "legacy")
    legacy.ensure_dirs()
    config = alembic_config(legacy)
    assert config is not None
    command.upgrade(config, "558a25772f08")

    engine = sa.create_engine(f"sqlite:///{legacy.db_path}")
    with engine.begin() as connection:
        connection.execute(
            sa.text(
                "INSERT INTO projects (id, name, description, purpose, created_at, updated_at) "
                "VALUES ('prj_legacy', 'Legacy', '', '', '2026-10-29 00:00:00', '2026-10-29 00:00:00')"
            )
        )
        connection.execute(
            sa.text(
                "INSERT INTO structures (id, project_id, target_id, source, accession, format, "
                "rel_path, sha256, quality, created_at) VALUES "
                "('str_legacy', 'prj_legacy', NULL, 'upload', NULL, 'pdb', "
                "'uploads/legacy.pdb', :sha, '{}', '2026-10-29 00:00:00')"
            ),
            {"sha": "a" * 64},
        )
    engine.dispose()

    command.upgrade(config, "head")

    engine = sa.create_engine(f"sqlite:///{legacy.db_path}")
    with engine.connect() as connection:
        row = connection.execute(sa.text("SELECT id, license FROM structures WHERE id = 'str_legacy'")).one()
    engine.dispose()
    assert row.id == "str_legacy"
    assert row.license == "unknown"


def test_installed_wheel_layout_migrates_with_packaged_scripts(settings, tmp_path, monkeypatch):
    """A wheel has no alembic.ini; it must still run Alembic and record a revision."""
    import shutil

    from hcs_discovery.core.config import Settings
    from hcs_discovery.database import migrations

    packaged = tmp_path / "pkg" / "_alembic"
    shutil.copytree(migrations.PROJECT_ROOT / "migrations", packaged, ignore=shutil.ignore_patterns("__pycache__"))
    monkeypatch.setattr(migrations, "PROJECT_ROOT", tmp_path / "no-checkout")
    monkeypatch.setattr(migrations, "PACKAGED_SCRIPTS", packaged)

    wheel_settings = Settings(data_dir=tmp_path / "wheel-data")
    wheel_settings.ensure_dirs()
    assert migrations.upgrade_database(wheel_settings) == "alembic"
    assert migrations.current_revision(wheel_settings) == current_revision(settings)
